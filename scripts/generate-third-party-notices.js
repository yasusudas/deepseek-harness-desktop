#!/usr/bin/env node

const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const ROOT = path.join(__dirname, '..');
const BUNDLE = path.join(ROOT, 'bundle', 'dsh');
const OUTPUT = path.join(ROOT, 'THIRD_PARTY_NOTICES.md');

function walkPackageDirs(root) {
  if (!fs.existsSync(root)) return [];

  const results = [];
  const visit = (dir) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const fullPath = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        if (entry.name === '.cache') continue;
        visit(fullPath);
        continue;
      }
      if (entry.isFile() && entry.name === 'package.json') {
        results.push(path.dirname(fullPath));
      }
    }
  };

  visit(root);
  return results;
}

function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, 'utf8'));
}

function normalizeLicense(pkg) {
  if (typeof pkg.license === 'string') return pkg.license;
  if (pkg.license && typeof pkg.license.type === 'string') return pkg.license.type;
  if (Array.isArray(pkg.licenses)) {
    return pkg.licenses.map((item) => item.type || item).filter(Boolean).join(' / ') || 'SEE PACKAGE LICENSE';
  }
  return 'SEE PACKAGE LICENSE';
}

function normalizeSource(pkg) {
  const repository = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url;
  const source = repository || pkg.homepage;
  if (!source) return '';
  return source
    .replace(/^git\+/, '')
    .replace(/\.git$/, '')
    .replace(/^git@github\.com:/, 'https://github.com/')
    .replace(/^github:/, 'https://github.com/');
}

function findLicenseFiles(packageDir) {
  return fs.readdirSync(packageDir)
    .filter((name) => /^(license|licence|copying|notice)(\.|$)/i.test(name))
    .sort();
}

function packageRecord(packageDir, packageRoot) {
  const pkg = readJson(path.join(packageDir, 'package.json'));
  if (!pkg.name || !pkg.version) return null;

  return {
    name: pkg.name,
    version: pkg.version,
    license: normalizeLicense(pkg),
    source: normalizeSource(pkg),
    location: path.relative(packageRoot, packageDir) || '.',
    licenseFiles: findLicenseFiles(packageDir),
  };
}

function mergePackages(records) {
  const merged = new Map();
  for (const record of records.filter(Boolean)) {
    const key = `${record.name}@${record.version}`;
    const existing = merged.get(key);
    if (!existing) {
      merged.set(key, { ...record, locations: [record.location] });
      continue;
    }
    existing.locations.push(record.location);
    existing.licenseFiles = [...new Set([...existing.licenseFiles, ...record.licenseFiles])].sort();
  }
  return [...merged.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
}

function runtimeVersion() {
  const node = path.join(BUNDLE, 'node', 'bin', 'node');
  if (!fs.existsSync(node)) return 'unknown';
  return execFileSync(node, ['--version'], { encoding: 'utf8' }).trim().replace(/^v/, '');
}

function markdownCell(value) {
  return String(value || '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
}

function render(records) {
  const electronPackage = readJson(require.resolve('electron/package.json'));
  const electronDir = path.dirname(require.resolve('electron/package.json'));
  const electronLicenses = findLicenseFiles(electronDir);
  const nodeVersion = runtimeVersion();
  const generatedAt = new Date().toISOString().slice(0, 10);

  const lines = [
    '<!-- Generated by scripts/generate-third-party-notices.js. Do not edit by hand. -->',
    '<!-- Regenerate after npm run prepare-bundle. -->',
    '# Third-Party Notices',
    '',
    'DeepSeek Harness Desktop is licensed under [MIT](LICENSE). This file describes the third-party software included in the distributable bundle. Each project remains under its own license; nothing here changes those terms.',
    '',
    `Generated from the current bundle on ${generatedAt}. The runtime bundle is rebuilt by [scripts/prepare-bundle.js](scripts/prepare-bundle.js).`,
    '',
    '## Runtime npm dependencies',
    '',
    '| Package | Version | License | Source | License files in bundle |',
    '| --- | --- | --- | --- | --- |',
  ];

  for (const record of records) {
    const files = record.licenseFiles.length
      ? record.licenseFiles.join(', ')
      : 'package.json license field';
    const source = record.source ? `[source](${record.source})` : '';
    const locations = record.locations.map((location) => `dsh/${location}`).join(', ');
    lines.push(`| ${markdownCell(record.name)} | ${markdownCell(record.version)} | ${markdownCell(record.license)} | ${source} | ${markdownCell(files)} (${markdownCell(locations)}) |`);
  }

  lines.push(
    '',
    '## Bundled runtimes',
    '',
    '| Component | Version | License files |',
    '| --- | --- | --- |',
    `| Node.js | ${markdownCell(nodeVersion)} | dsh/node/LICENSE and dsh/node/README.md |`,
    `| Electron | ${markdownCell(electronPackage.version)} | ${markdownCell(electronLicenses.join(', ') || 'Electron package license files')} |`,
    '',
    'Electron also distributes Chromium and other embedded components. Their notices are shipped with the Electron runtime and remain under the terms provided by Electron.',
    '',
    '## Build-time tooling',
    '',
    'The repository uses Electron Builder to assemble the application. It is a build-time dependency and is not included as an application runtime dependency. Its license is available from `node_modules/electron-builder/package.json` during development.',
    '',
    '## Attribution',
    '',
    '- DeepSeek Harness: https://github.com/deepseek-ai/deepseek-harness',
    '- This fork adds an Electron wrapper, multilingual localization, and macOS window integration.',
    '',
  );

  return `${lines.join('\n')}\n`;
}

function main() {
  const nodeModules = path.join(BUNDLE, 'lib', 'node_modules');
  if (!fs.existsSync(nodeModules)) {
    throw new Error(`Runtime bundle is missing: ${nodeModules}. Run npm run prepare-bundle first.`);
  }

  const records = mergePackages(walkPackageDirs(nodeModules).map((dir) => packageRecord(dir, BUNDLE)));
  const rendered = render(records);

  if (process.argv.includes('--check')) {
    const current = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, 'utf8') : '';
    if (current !== rendered) {
      console.error(`Third-party notices are stale: ${OUTPUT}`);
      process.exitCode = 1;
      return;
    }
    console.log('Third-party notices are up to date.');
    return;
  }

  fs.writeFileSync(OUTPUT, rendered);
  console.log(`Generated ${OUTPUT} (${records.length} runtime packages).`);
}

main();
